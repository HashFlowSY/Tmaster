/** 两份文档的登记表；键与路由 `?doc=` 参数一致。 */
export const LEGAL_DOCS: Record<LegalDocKey, LegalDoc> = {
  terms: TERMS,
  privacy: PRIVACY,
};

/**
 * 把路由参数解析为要展示的文档：`'privacy'` → 隐私政策，其余（含缺省 / 数组 / 非法值）→ 用户协议。
 * 抽为纯函数以便单测，令路由页保持薄接线（spec Testing Decisions：屏幕只接线、逻辑走可测纯模块）。
 */
export function resolveLegalDoc(param?: string | string[]): LegalDoc {
  const key = Array.isArray(param) ? param[0] : param;
  return key === 'privacy' ? LEGAL_DOCS.privacy : LEGAL_DOCS.terms;
}
